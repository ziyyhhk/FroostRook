'use strict';

/*
 * Compiles book.js into native/book_data.h so the bare .exe has the same
 * opening book as the Node front-end. Keys are the same "board side castling"
 * strings, hashed with 64-bit FNV-1a; the C++ side rebuilds that string from
 * the live position and binary-searches the table.
 *
 *   node test/gen-native-book.js
 */

const fs = require('fs');
const path = require('path');
const { BOOK } = require('../book.js');

const OUT = path.join(__dirname, '..', 'native', 'book_data.h');

function fnv1a(s) {
  let h = 14695981039346656037n;
  for (let i = 0; i < s.length; i++) {
    h ^= BigInt(s.charCodeAt(i));
    h = BigInt.asUintN(64, h * 1099511628211n);
  }
  return h;
}

const PROMO = { n: 2, b: 3, r: 4, q: 5 };

function encodeMove(uci) {
  const from = (uci.charCodeAt(1) - 49) * 16 + (uci.charCodeAt(0) - 97);
  const to = (uci.charCodeAt(3) - 49) * 16 + (uci.charCodeAt(2) - 97);
  const promo = uci.length > 4 ? PROMO[uci[4]] || 0 : 0;
  return (from | (to << 7) | (promo << 14)) >>> 0;
}

const keys = Object.keys(BOOK);
const entries = [];
const moves = [];
const seen = new Map();
let moveCount = 0;

for (const key of keys) {
  const h = fnv1a(key);
  if (seen.has(h)) throw new Error(`FNV collision: ${seen.get(h)} / ${key}`);
  seen.set(h, key);
  const list = BOOK[key].map(([uci, w]) => {
    const mv = encodeMove(uci);
    if (!mv) throw new Error('bad book move ' + uci);
    return { mv, w };
  });
  entries.push({ key: h, off: moveCount, count: list.length });
  for (const m of list) moves.push(m);
  moveCount += list.length;
}

entries.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));

const lines = [];
lines.push('// Generated by test/gen-native-book.js from book.js. Do not edit by hand.');
lines.push('// Keys are 64-bit FNV-1a hashes of "board side castling" (no ep field).');
lines.push('#pragma once');
lines.push('#include <cstdint>');
lines.push('');
lines.push('namespace bookdata {');
lines.push('struct Move { uint32_t move; uint16_t weight; };');
lines.push('struct Entry { uint64_t key; uint32_t offset; uint16_t count; };');
lines.push('');
lines.push(`static constexpr Move MOVES[] = {`);
for (const m of moves) lines.push(`  {${m.mv}u, ${m.w}},`);
lines.push('};');
lines.push('');
lines.push(`static constexpr Entry ENTRIES[] = {`);
for (const e of entries) lines.push(`  {${e.key}ULL, ${e.off}, ${e.count}},`);
lines.push('};');
lines.push('');
lines.push(`static constexpr uint32_t MOVE_COUNT = ${moves.length};`);
lines.push(`static constexpr uint32_t ENTRY_COUNT = ${entries.length};`);
lines.push('} // namespace bookdata');
lines.push('');

fs.writeFileSync(OUT, lines.join('\n'));
console.log(`native/book_data.h written: ${entries.length} positions, ${moves.length} moves, ` +
            `${(fs.statSync(OUT).size / 1024).toFixed(0)} KB`);
